//! Color theme tokens for light and dark appearance.
//!
//! Every screen reads colors through the `t!` macro in the parent `ui` module,
//! which resolves a token against the active theme.  Light is the default; the
//! user can switch to dark in Settings (persisted as `ui.dark_mode` in
//! marina.toml).  All dark text colors are chosen for >= 4.5:1 contrast on
//! their backgrounds.

#[derive(Clone, Copy)]
